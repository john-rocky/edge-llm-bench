#!/bin/bash
# Wraps the iOS xcframeworks an ExecuTorch checkout built locally (scripts/build_apple_frameworks.sh,
# into <checkout>/cmake-out) as the local SwiftPM package ios/BenchmarkApp/project-ddp-executorch.yml
# links: ios/BenchmarkApp/Vendored/executorch.
#
# Why a wrapper and not the checkout's own Package.swift: that manifest declares every product the
# script can build (Core ML, TorchAO, the _debug variants, three slices) as a binary target, and SwiftPM
# refuses a package whose binary target path is missing; the lab build needs the iOS slice of the
# Release frameworks the app links and nothing else. Product names, dependencies and linker settings
# are the checkout's (executorch, executorch_llm, backend_xnnpack, backend_mlx, kernels_llm,
# kernels_optimized, kernels_quantized; threadpool and kleidiai as dependencies), and the MLX
# delegate's metallib ships as a resource bundle the way the checkout's manifest does it
# (backend_mlx_resources, mlx-ios.metallib), since MLX loads it at run time by name.
#
# Usage: ios/ddp/make_executorch_package.sh <executorch checkout> [<tag>] [<patches line>...]
#   <tag> goes to Vendored/executorch.tag and each patches line to Vendored/executorch.patches; both
#   end up in the app's engine pins (scripts/stamp_engine_pins.sh).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
APP_DIR="$(cd "$HERE/../BenchmarkApp" && pwd)"
SRC="$(cd "${1:?usage: $0 <executorch checkout> [tag] [patch...]}" && pwd)"
TAG="${2:-}"
shift $(( $# >= 2 ? 2 : 1 ))
OUT="$APP_DIR/Vendored/executorch"
FW="$SRC/cmake-out"

need=(executorch executorch_llm backend_xnnpack backend_mlx kernels_llm kernels_optimized kernels_quantized threadpool)
for n in "${need[@]}"; do
  if [ ! -d "$FW/$n.xcframework" ]; then
    echo "no $FW/$n.xcframework: build it with scripts/build_apple_frameworks.sh --Release --xnnpack --mlx --llm --optimized --quantized" >&2
    exit 2
  fi
done
METALLIB="$SRC/.Package.swift/backend_mlx_resources/mlx-ios.metallib"
if [ ! -f "$METALLIB" ]; then
  echo "no $METALLIB: the MLX delegate's Metal kernels (build_apple_frameworks.sh writes them when MLX is on)" >&2
  exit 2
fi

rm -rf "$OUT"
mkdir -p "$OUT/Frameworks" "$OUT/Sources/backend_mlx_resources"
for n in "${need[@]}" kleidiai; do
  if [ -d "$FW/$n.xcframework" ]; then
    cp -R "$FW/$n.xcframework" "$OUT/Frameworks/"
  fi
done
cp "$METALLIB" "$OUT/Sources/backend_mlx_resources/mlx-ios.metallib"
# A target with no source is not a Swift target to SwiftPM (it then looks for C headers in include/).
echo "// The resource bundle's target: SwiftPM needs a source." > "$OUT/Sources/backend_mlx_resources/dummy.swift"
HAS_KLEIDIAI=false
[ -d "$OUT/Frameworks/kleidiai.xcframework" ] && HAS_KLEIDIAI=true

for n in executorch executorch_llm backend_xnnpack backend_mlx kernels_llm kernels_optimized kernels_quantized; do
  mkdir -p "$OUT/Sources/${n}_with_dependencies"
  echo "// SwiftPM needs a source per target; the library is the binary target this depends on." \
    > "$OUT/Sources/${n}_with_dependencies/dummy.swift"
done

cat > "$OUT/Package.swift" <<EOF
// swift-tools-version:5.9
// Generated by ios/ddp/make_executorch_package.sh from the frameworks of
// $SRC (cmake-out). Do not edit: regenerate.
import PackageDescription

let kleidiai = $HAS_KLEIDIAI
let products: [(String, [String], [LinkerSetting])] = [
  ("executorch", [], [
    .linkedFramework("Accelerate"), .linkedFramework("CoreGraphics"), .linkedFramework("CoreImage"),
    .linkedFramework("CoreVideo"), .linkedFramework("Foundation"), .linkedLibrary("c++"),
  ]),
  ("executorch_llm", ["executorch"], []),
  ("backend_xnnpack", (kleidiai ? ["kleidiai"] : []) + ["threadpool"], []),
  ("backend_mlx", [], [.linkedFramework("Metal"), .linkedFramework("Foundation"), .linkedFramework("QuartzCore")]),
  ("kernels_llm", [], []),
  ("kernels_optimized", (kleidiai ? ["kleidiai"] : []) + ["threadpool"], [.linkedFramework("Accelerate")]),
  ("kernels_quantized", [], []),
]

var targets: [Target] = [.binaryTarget(name: "threadpool", path: "Frameworks/threadpool.xcframework")]
if kleidiai {
  targets.append(.binaryTarget(name: "kleidiai", path: "Frameworks/kleidiai.xcframework"))
}
targets.append(.target(name: "backend_mlx_resources", path: "Sources/backend_mlx_resources",
                       resources: [.copy("mlx-ios.metallib")]))
for (name, deps, linker) in products {
  targets.append(.binaryTarget(name: name, path: "Frameworks/\(name).xcframework"))
  var dependencies: [Target.Dependency] = ([name] + deps).map { .target(name: \$0) }
  if name == "backend_mlx" {
    dependencies.append(.target(name: "backend_mlx_resources"))
  }
  targets.append(.target(name: "\(name)_with_dependencies", dependencies: dependencies,
                         path: "Sources/\(name)_with_dependencies", linkerSettings: linker))
}

let package = Package(
  name: "executorch",
  platforms: [.iOS(.v17)],
  products: products.map { .library(name: \$0.0, targets: ["\(\$0.0)_with_dependencies"]) },
  targets: targets
)
EOF

V="$APP_DIR/Vendored"
# The checkout's commit, for the engine pins (the wrapper package has no .git of its own); none for
# an unpacked source tarball, whose <tag> then names it.
if REV="$(git -C "$SRC" rev-parse --verify -q HEAD 2>/dev/null)"; then
  printf '%s\n' "$REV" > "$V/executorch.rev"
else
  rm -f "$V/executorch.rev"
fi
if [ -n "$TAG" ]; then
  printf '%s\n' "$TAG" > "$V/executorch.tag"
else
  rm -f "$V/executorch.tag"
fi
if [ $# -gt 0 ]; then
  printf '%s\n' "$@" > "$V/executorch.patches"
else
  rm -f "$V/executorch.patches"
fi
echo "executorch package -> $OUT ($(ls "$OUT/Frameworks" | tr '\n' ' '))"
